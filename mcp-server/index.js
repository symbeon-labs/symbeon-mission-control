// Execute MCP Tool Handler
function handleToolCall(name, args) {
  switch (name) {
    case 'mc_get_governance_state': {
      const data = liveGovernance.getDashboardData();
      return { content: [{ type: 'text', text: JSON.stringify(data, null, 2) }] };
    }
    case 'mc_evaluate_policies': {
      const state = liveGovernance.getCurrentState();
      return { content: [{ type: 'text', text: JSON.stringify(state.violations, null, 2) }] };
    }
    case 'mc_get_recommendations': {
      const state = liveGovernance.getCurrentState();
      return { content: [{ type: 'text', text: JSON.stringify(state.recommendations, null, 2) }] };
    }
    case 'mc_create_operational_object': {
      const newObj = {
        id: `${args.type.toUpperCase()}-${Date.now().toString().slice(-4)}`,
        type: args.type,
        title: args.title,
        description: args.description || '',
        owner: args.owner || 'Agent',
        status: args.status || 'draft',
        created_at: new Date().toISOString()
      };
      
      liveGovernance.onObjectModified(newObj.id, newObj.type, newObj.owner);
      return { content: [{ type: 'text', text: JSON.stringify({ message: 'Object created successfully', object: newObj }, null, 2) }] };
    }
    case 'mc_relate_objects': {
      const relation = graphManager.createRelation(
        args.sourceId,
        args.targetId,
        args.sourceType || 'Task',
        args.targetType || 'Milestone',
        args.relationType,
        'Agent'
      );
      liveGovernance.onGraphModified(relation.id, 'create', 'Agent');
      return { content: [{ type: 'text', text: JSON.stringify({ message: 'Relation created', relation }, null, 2) }] };
    }
    case 'mc_submit_evidence': {
      const evidenceId = `EVD-${Date.now().toString().slice(-4)}`;
      const relation = graphManager.createRelation(
        args.targetObjectId,
        evidenceId,
        'Task',
        'Evidence',
        'PROVES',
        'Agent',
        { sourceUrl: args.sourceUrl, type: args.evidenceType, title: args.title }
      );
      liveGovernance.onGraphModified(relation.id, 'create', 'Agent');
      return { content: [{ type: 'text', text: JSON.stringify({ message: 'Evidence attached and verified', evidenceId, relation }, null, 2) }] };
    }
    default:
      throw new Error(`Unknown tool: ${name}`);
  }
}

// JSON-RPC stdio Handler
const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout,
  terminal: false
});

rl.on('line', (line) => {
  if (!line.trim()) return;
  try {
    const request = JSON.parse(line);
    const { id, method, params } = request;

    if (method === 'initialize') {
      sendResponse(id, {
        protocolVersion: '2024-11-05',
        capabilities: { tools: {} },
        serverInfo: { name: 'symbeon-mission-control', version: '1.0.0' }
      });
    } else if (method === 'notifications/initialized') {
      // Acknowledged
    } else if (method === 'tools/list') {
      sendResponse(id, { tools: TOOLS });
    } else if (method === 'tools/call') {
      const result = handleToolCall(params.name, params.arguments || {});
      sendResponse(id, result);
    } else {
      sendError(id, -32601, `Method not found: ${method}`);
    }
  } catch (err) {
    sendError(null, -32700, `Parse error: ${err.message}`);
  }
});

function sendResponse(id, result) {
  const msg = JSON.stringify({ jsonrpc: '2.0', id, result });
  process.stdout.write(msg + '\n');
}

function sendError(id, code, message) {
  const msg = JSON.stringify({ jsonrpc: '2.0', id, error: { code, message } });
  process.stdout.write(msg + '\n');
}
