import fs from 'fs';
import path from 'path';
import readline from 'readline';
import { fileURLToPath } from 'url';

import { GraphManager } from '../src/js/graph/GraphManager.js';
import { LiveGovernance } from '../src/js/governance/LiveGovernance.js';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT_DIR = path.resolve(__dirname, '..');
const PROJECT_ID = 'guarddrive';
const STORAGE_DIR = path.join(ROOT_DIR, 'storage', 'projects', PROJECT_ID);

// Initialize Graph and LiveGovernance
const graphManager = new GraphManager();
const liveGovernance = new LiveGovernance(graphManager);

// Data store
let projectData = {};

function loadProjectData() {
  const files = ['tasks', 'milestones', 'decisions', 'documents', 'evidence', 'releases', 'risk'];
  const data = [];

  for (const file of files) {
    const filePath = path.join(STORAGE_DIR, `${file}.json`);
    if (fs.existsSync(filePath)) {
      try {
        const json = JSON.parse(fs.readFileSync(filePath, 'utf-8'));
        const items = json[file] || json.tasks || json.risks || [];
        const typeName = file.charAt(0).toUpperCase() + file.slice(1).replace(/s$/, '');
        
        items.forEach(item => {
          data.push({
            ...item,
            type: item.type || typeName
          });
        });
        projectData[file] = json;
      } catch (err) {
        console.error(`Error loading ${file}.json:`, err.message);
      }
    }
  }

  liveGovernance.initialize(data);
}

// Initial load
loadProjectData();

// Define Available MCP Tools based on MCS-0004
